"""Supply-chain pins: what CI and the images install is exactly what was reviewed.

- every GitHub Action is pinned to a full commit SHA (a tag can be moved);
- every Dockerfile base image is pinned by digest;
- every Python install is hash-locked, from a lock generated from its .in file;
- the API image installs only its runtime lock, not the test tooling;
- no npm dependency runs an install script, and CI audits what ships;
- Dependabot proposes updates only after a cooldown.
"""

from __future__ import annotations

import re
from pathlib import Path

import pytest

ROOT = Path(__file__).parent.parent
WORKFLOWS = sorted((ROOT / ".github" / "workflows").glob("*.yml"))
DOCKERFILES = sorted((ROOT / "docker").glob("*.Dockerfile"))
LOCKS = {
    "requirements.txt": "requirements.in",
    "requirements-api.txt": "requirements-api.in",
    "requirements-bot.txt": "requirements-bot.in",
    "docker/docs-requirements.txt": "docker/docs-requirements.in",
}
PIN = re.compile(r"^([A-Za-z0-9_.-]+)==([^ \\]+)", re.MULTILINE)


def _pins(lock: str) -> dict[str, str]:
    return {name.lower(): version for name, version in PIN.findall((ROOT / lock).read_text())}


@pytest.mark.parametrize("workflow", WORKFLOWS, ids=lambda p: p.name)
def test_every_action_is_pinned_to_a_commit(workflow: Path) -> None:
    uses = re.findall(r"uses: (\S+)", workflow.read_text())
    assert uses, workflow
    unpinned = [u for u in uses if not re.fullmatch(r"[\w.-]+/[\w./-]+@[0-9a-f]{40}", u)]
    assert unpinned == []


@pytest.mark.parametrize("dockerfile", DOCKERFILES, ids=lambda p: p.name)
def test_every_base_image_is_pinned_by_digest(dockerfile: Path) -> None:
    bases = re.findall(r"^FROM (\S+)", dockerfile.read_text(), re.MULTILINE)
    assert bases, dockerfile
    assert [b for b in bases if not re.search(r"@sha256:[0-9a-f]{64}$", b)] == []


@pytest.mark.parametrize("lock", LOCKS, ids=str)
def test_every_lock_is_generated_and_fully_hashed(lock: str) -> None:
    text = (ROOT / lock).read_text()
    assert "autogenerated by pip-compile" in text
    assert f"{Path(LOCKS[lock]).name}\n" in text  # compiled from its .in file
    entries = re.split(r"\n(?=[A-Za-z0-9_.-]+==)", text.split("\n\n", 1)[-1])
    packages = [e for e in entries if PIN.match(e)]
    assert packages
    assert [e.split(" ", 1)[0] for e in packages if "--hash=sha256:" not in e] == []


@pytest.mark.parametrize("lock", ["requirements.txt", "requirements-bot.txt"])
def test_locks_agree_with_the_api_versions(lock: str) -> None:
    """Constrained by requirements-api.txt: tests run the versions production runs."""
    api = _pins("requirements-api.txt")
    other = _pins(lock)
    assert {n: (v, other[n]) for n, v in api.items() if n in other and other[n] != v} == {}


def test_the_api_image_carries_no_test_tooling() -> None:
    api = _pins("requirements-api.txt")
    for tool in ("pytest", "hypothesis", "selenium", "numpy", "ruff", "bandit", "pip-audit", "coverage"):
        assert tool not in api, tool
    dockerfile = (ROOT / "docker" / "api.Dockerfile").read_text()
    assert "pip install --no-deps --require-hashes -r requirements-api.txt" in dockerfile


@pytest.mark.parametrize("dockerfile", DOCKERFILES, ids=lambda p: p.name)
def test_images_install_only_from_locks(dockerfile: Path) -> None:
    text = dockerfile.read_text()
    for line in re.findall(r"^RUN .*\b(?:pip|npm) .*$", text, re.MULTILINE):
        if " pip install" in line:
            assert "--require-hashes -r " in line, line
        if " npm " in line and " ci" in line:
            assert "npm ci --ignore-scripts" in line, line
        assert "npm install" not in line, line


def test_ci_installs_from_locks_and_audits() -> None:
    test = (ROOT / ".github" / "workflows" / "test.yml").read_text()
    assert "npm ci --ignore-scripts" in test and "\n        run: npm ci\n" not in test
    assert "npm audit --omit=dev --audit-level=high" in test
    assert "npx --no-install tsc" in test  # never fetch a package by name at run time
    installs = re.findall(r"pip install [^\n]*", test)
    assert installs and all("--require-hashes -r " in i for i in installs), installs
    for lock in LOCKS:
        assert lock in test, lock  # pip-audit covers every lock


def test_the_lead_agent_installs_pinned_tools() -> None:
    lead = (ROOT / ".github" / "workflows" / "lead-agent.yml").read_text()
    assert re.search(r'CLAUDE_CODE_VERSION: "\d+\.\d+\.\d+"', lead)
    assert lead.count('"@anthropic-ai/claude-code@${CLAUDE_CODE_VERSION}"') == 2
    assert "@anthropic-ai/claude-code\n" not in lead
    assert [i for i in re.findall(r"pip install [^\n]*", lead) if "--require-hashes" not in i] == []


def test_npm_never_runs_install_scripts_in_the_frontend() -> None:
    assert "ignore-scripts=true" in (ROOT / "frontend" / ".npmrc").read_text()


def test_dependabot_waits_out_a_cooldown_for_every_ecosystem() -> None:
    config = (ROOT / ".github" / "dependabot.yml").read_text()
    ecosystems = re.findall(r"package-ecosystem: (\S+)", config)
    assert sorted(set(ecosystems)) == ["docker", "github-actions", "npm", "pip"]
    assert config.count("cooldown: {default-days: 7}") == len(ecosystems)
    # docker-compose.yml is a host change (deploy_hook.sh): never auto-proposed.
    assert "docker-compose" not in re.findall(r"package-ecosystem: (\S+)", config)
